"""Rebuilds shared/utils/googleFonts.ts from Google's public font list.
Usage: curl -s https://fonts.google.com/metadata/fonts -o /tmp/gf.json && python3 scripts/google-fonts.py /tmp/gf.json"""
import json, re, sys
meta = json.load(open(sys.argv[1]))
CAT = {'Sans Serif': 's', 'Serif': 'r', 'Display': 'd', 'Handwriting': 'h', 'Monospace': 'm'}
rows = []
for f in sorted(meta['familyMetadataList'], key=lambda x: x.get('popularity', 99999)):
    name = f['family']
    if 'latin' not in f.get('subsets', []) or f.get('isNoto') or name.startswith(('Material ', 'Noto ')) or 'Icons' in name or 'Symbols' in name:
        continue
    if not re.fullmatch(r"[A-Za-z0-9 ]{2,60}", name):
        continue
    wght = next((a for a in f.get('axes', []) if a['tag'] == 'wght'), None)
    if wght:
        w = f"{int(wght['min'])}-{int(wght['max'])}"
    else:
        ws = sorted({int(k) for k in f['fonts'] if k.isdigit()})
        if not ws:
            continue
        w = ','.join(map(str, ws))
    rows.append(f"{name}|{CAT.get(f['category'], 's')}|{w}")
out = '''// Generated by scripts/google-fonts.py from Google's public font list. Don't edit by hand.
// Each entry: "Family|kind|weights". kind: s sans, r serif, d display, h handwriting, m mono.
// weights: "min-max" for variable fonts, else a list of the upright weights it has.
// Ordered most popular first. Imported by the server and the Theme page only (it's ~50 KB).
export const GOOGLE_FONTS_RAW = %s
''' % json.dumps('\n'.join(rows))
open('shared/utils/googleFonts.ts', 'w').write(out)
print(len(rows), 'fonts,', len(out) // 1024, 'KB')
